function applyScrollRotations(index = 0) {
    const rotations = scrollRotationsByPage[index] || scrollRotationsByPage[0];
    const rectangleTop = document.querySelector('.rectangle-5');
    const rectangleBottom = document.querySelector('.rectangle-faltante');

    document.documentElement.style.setProperty('--scrollbox-top-rotation', rotations.top);
    document.documentElement.style.setProperty('--scrollbox-bottom-rotation', rotations.bottom);

    if (rectangleTop) {
        rectangleTop.style.transform = `rotate(${rotations.top})`;
    }
    if (rectangleBottom) {
        rectangleBottom.style.transform = `rotate(${rotations.bottom})`;
    }
}

