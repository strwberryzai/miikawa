document.addEventListener('DOMContentLoaded', function() {
    changeContent(0);

    document.addEventListener('click', function(event) {
        if (currentPage !== 0) {
            return;
        }

        const imageArea = document.querySelector('.imagen-arriba');
        const clickedElement = event.target;
        const imageBounds = imageArea ? imageArea.getBoundingClientRect() : null;
        const clickedInsideImage = imageBounds &&
            event.clientX >= imageBounds.left &&
            event.clientX <= imageBounds.right &&
            event.clientY >= imageBounds.top &&
            event.clientY <= imageBounds.bottom;

        if (clickedInsideImage && !clickedElement.closest('.rectangle-5, .rectangle-faltante')) {
            nextPage();
        }
    });
});